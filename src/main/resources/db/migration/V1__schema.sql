create table store (
    id           bigint generated by default as identity primary key,
    code         varchar(12)  not null unique,
    name         varchar(120) not null,
    address      varchar(255),
    auto_reorder boolean      not null default false,
    created_at   timestamptz  not null default now()
);

create table supplier (
    id              bigint generated by default as identity primary key,
    name            varchar(120)  not null unique,
    email           varchar(200),
    phone           varchar(40),
    lead_time_days  integer       not null default 2 check (lead_time_days >= 0),
    min_order_value numeric(12,2) not null default 0 check (min_order_value >= 0),
    notes           varchar(1000)
);

create table product (
    id          bigint generated by default as identity primary key,
    sku         varchar(32)   not null unique,
    name        varchar(160)  not null,
    category    varchar(60)   not null,
    unit        varchar(20)   not null,
    pack_size   integer       not null default 1 check (pack_size > 0),
    unit_cost   numeric(12,2) not null check (unit_cost >= 0),
    barcode     varchar(32) unique,
    supplier_id bigint        not null references supplier (id),
    active      boolean       not null default true
);

create table stock_level (
    id         bigint generated by default as identity primary key,
    store_id   bigint      not null references store (id),
    product_id bigint      not null references product (id),
    on_hand    integer     not null default 0 check (on_hand >= 0),
    par        integer     not null default 0 check (par >= 0),
    bin        varchar(40),
    version    bigint      not null default 0,
    unique (store_id, product_id)
);

create table purchase_order (
    id          bigint generated by default as identity primary key,
    store_id    bigint      not null references store (id),
    supplier_id bigint      not null references supplier (id),
    status      varchar(24) not null,
    source      varchar(12) not null,
    notes       varchar(500),
    created_at  timestamptz not null,
    sent_at     timestamptz,
    expected_on date,
    closed_at   timestamptz,
    version     bigint      not null default 0
);

create index purchase_order_store_status_idx on purchase_order (store_id, status);

create table order_line (
    id         bigint generated by default as identity primary key,
    order_id   bigint        not null references purchase_order (id) on delete cascade,
    product_id bigint        not null references product (id),
    quantity   integer       not null check (quantity > 0),
    received   integer       not null default 0 check (received >= 0),
    unit_cost  numeric(12,2) not null
);

create index order_line_order_idx on order_line (order_id);

create table stock_movement (
    id            bigint generated by default as identity primary key,
    store_id      bigint      not null references store (id),
    product_id    bigint      not null references product (id),
    delta         integer     not null,
    balance_after integer     not null,
    reason        varchar(20) not null,
    reference     varchar(40),
    note          varchar(255),
    occurred_at   timestamptz not null
);

create index stock_movement_store_time_idx on stock_movement (store_id, occurred_at desc);
create index stock_movement_level_idx on stock_movement (store_id, product_id, occurred_at desc);

create table stock_take (
    id           bigint generated by default as identity primary key,
    store_id     bigint      not null references store (id),
    status       varchar(20) not null,
    blind        boolean     not null default true,
    started_at   timestamptz not null,
    completed_at timestamptz
);

create table stock_take_line (
    id            bigint generated by default as identity primary key,
    stock_take_id bigint        not null references stock_take (id) on delete cascade,
    product_id    bigint        not null references product (id),
    bin           varchar(40),
    expected      integer       not null,
    counted       integer check (counted >= 0),
    unit_cost     numeric(12,2) not null,
    unique (stock_take_id, product_id)
);
